#!/usr/bin/env python3
"""Turns an extracted MindTheGapps package (system/product, system/system_ext) into a vendor/gapps tree
that builds inline, the way MindTheGapps' own vendor_gapps does: android_app_import for every APK,
prebuilt_etc for config files, dex_import for framework jars, an Android.mk for the prebuilt overlay APKs
and PRODUCT_COPY_FILES for native libraries. Product makefile: gapps.mk (inherit it from the device).

Usage: gen-gapps.py <extracted package dir (holds system/)> <output dir, e.g. src-mods/vendor/gapps>
"""
import os, shutil, sys

APP_IMPORT = '''
android_app_import {
    name: "%(name)s",
    owner: "gapps",
    apk: "%(apk)s",
    preprocessed: true,
    presigned: true,
    dex_preopt: {
        enabled: false,
    },%(priv)s
    %(partition)s_specific: true,
}
'''
ETC = '''
prebuilt_etc {
    name: "%(name)s",
    owner: "gapps",
    src: "%(src)s",
    sub_dir: "%(sub_dir)s",
    filename_from_src: true,
    %(partition)s_specific: true,
}
'''
DEX = '''
dex_import {
    name: "%(name)s",
    owner: "gapps",
    jars: ["%(src)s"],
    %(partition)s_specific: true,
}
'''
LIB = '''
cc_prebuilt_library_shared {
    name: "%(name)s",
    owner: "gapps",
    strip: {
        none: true,
    },
    target: {%(targets)s
    },
    compile_multilib: "both",
    check_elf_files: false,
    %(partition)s_specific: true,
}
'''
LIB_TARGET = '''
        android_%(arch)s: {
            srcs: ["%(src)s"],
        },'''
OVERLAY_MK = '''
include $(CLEAR_VARS)
LOCAL_MODULE := %(name)s
LOCAL_MODULE_OWNER := gapps
LOCAL_SRC_FILES := %(src)s
LOCAL_MODULE_CLASS := APPS
LOCAL_MODULE_TAGS := optional
LOCAL_MODULE_SUFFIX := .apk
LOCAL_CERTIFICATE := PRESIGNED
LOCAL_PRODUCT_MODULE := true
LOCAL_MODULE_PATH := $(TARGET_OUT_PRODUCT)/overlay
LOCAL_DEX_PREOPT := false
include $(BUILD_PREBUILT)
'''


def main():
    # optional: the tree path of the output (default vendor/gapps), and --tv (the Google TV pack:
    # no ro.setupwizard.mode, TV provisioning comes from device/google/atv)
    args = [a for a in sys.argv[1:] if a != '--tv']
    tv = '--tv' in sys.argv
    src, out = args[0], args[1]
    tree_path = args[2] if len(args) > 2 else 'vendor/gapps'
    prop = os.path.join(out, 'proprietary')
    if os.path.exists(prop):
        shutil.rmtree(prop)
    packages, copy_files, bp, mk = [], [], ['// Generated by gen-gapps.py from MindTheGapps. DO NOT MODIFY\n\nsoong_namespace {\n}\n'], \
        ['# Generated by gen-gapps.py from MindTheGapps. DO NOT MODIFY\nLOCAL_PATH := $(call my-dir)\n']
    libs = {}  # (partition, name) -> {arch: src}: ELF files must be Soong modules, not PRODUCT_COPY_FILES
    for partition in ('product', 'system_ext'):
        root = os.path.join(src, 'system', partition)
        for dirpath, _, files in os.walk(root):
            for f in sorted(files):
                full = os.path.join(dirpath, f)
                rel = os.path.relpath(full, os.path.join(src, 'system')).replace('\\', '/')  # product/app/X/X.apk
                dst = os.path.join(prop, rel)
                os.makedirs(os.path.dirname(dst), exist_ok=True)
                shutil.copyfile(full, dst)
                bp_src = 'proprietary/' + rel
                parts = rel.split('/')  # [partition, kind, ...]
                kind = parts[1]
                name, ext = os.path.splitext(f)
                if kind in ('app', 'priv-app') and ext == '.apk':
                    bp.append(APP_IMPORT % dict(name=name, apk=bp_src, partition=partition,
                                                priv='\n    privileged: true,' if kind == 'priv-app' else ''))
                    packages.append(name)
                elif kind == 'overlay' and ext == '.apk':
                    mk.append(OVERLAY_MK % dict(name=name, src=bp_src))
                    packages.append(name)
                elif kind == 'etc':
                    sub_dir = '/'.join(parts[2:-1])
                    bp.append(ETC % dict(name=f, src=bp_src, sub_dir=sub_dir, partition=partition))
                    packages.append(f)
                elif kind == 'framework' and ext == '.jar':
                    bp.append(DEX % dict(name=name, src=bp_src, partition=partition))
                    packages.append(name)
                elif kind in ('lib', 'lib64') and ext == '.so':
                    libs.setdefault((partition, name), {})['x86_64' if kind == 'lib64' else 'x86'] = bp_src
                else:
                    raise SystemExit('unhandled file: ' + rel)
    for (partition, name), srcs in sorted(libs.items()):
        bp.append(LIB % dict(name=name, partition=partition,
                             targets=''.join(LIB_TARGET % dict(arch=a, src=s) for a, s in sorted(srcs.items()))))
        packages.append(name)
    open(os.path.join(out, 'Android.bp'), 'w', newline='\n').write(''.join(bp))
    open(os.path.join(out, 'Android.mk'), 'w', newline='\n').write(''.join(mk))
    gapps_mk = ['# Generated by gen-gapps.py: %s for x86_64, built in. DO NOT MODIFY\n'
                % ('Google TV apps (Android 16 Google TV emulator image)' if tv else 'MindTheGapps'),
                'LOCAL_PATH := %s\n\n' % tree_path,
                'PRODUCT_SOONG_NAMESPACES += $(LOCAL_PATH)\n\n',
                'PRODUCT_PACKAGES += \\\n' + ' \\\n'.join('    ' + p for p in packages) + '\n\n']
    if copy_files:
        gapps_mk.append('PRODUCT_COPY_FILES += \\\n' + ' \\\n'.join('    ' + c for c in copy_files) + '\n\n')
    if not tv:
        gapps_mk.append('# Google setup wizard instead of the AOSP one; GMS-aware settings\n'
                        'PRODUCT_SYSTEM_PROPERTIES += \\\n    ro.setupwizard.mode=OPTIONAL\n')
    open(os.path.join(out, 'gapps.mk'), 'w', newline='\n').write(''.join(gapps_mk))
    print('%d packages, %d copy files -> %s' % (len(packages), len(copy_files), out))


if __name__ == '__main__':
    main()
